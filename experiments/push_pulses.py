"""Push the arm at its tip with short pulses all along the reach, every arm alike (Stage 2).

    uv run python experiments/push_pulses.py experiments/manual_demonstration_v2_esn_dynamics/push_pulses.toml

The arm reaches from the take's start posture with one tracker setting
(``[tracker]``, as in ``robot_esn.py``), its reference generated by each ESN of the
``[[esn]]`` tables (``key``, ``label``, and ``model``, an ``esn.toml`` of a run,
relative to the storage root), by the take replayed by time (``replay``), and by
the take replayed by the arm's progress (``progress``, configured by the
``[progress]`` table). The ESNs must have been trained on the same take. Each arm
reaches once undisturbed, and once under each pulse of ``[pulses]``, one pulse a
run: a constant tip force of each of ``forces`` newtons for ``duration`` seconds,
from each of ``onsets`` (task time, s), at each of ``angles_deg`` counterclockwise
from the direction toward the target (see :mod:`arm_esn_ctrl.disturbances`).

The run directory receives:

- ``metrics.csv``: one row per arm and pulse, the undisturbed runs with an empty
  pulse, with ``robot_esn.py``'s metrics of the run (``robot_esn.arm_metrics``),
  and three against the same arm's undisturbed run: ``arrival_shift_s``, how much
  later the arm arrives; ``setback``, how far back along the take's joint path the
  arm goes after the onset, as a fraction of the path (``robot_esn.progress``);
  and ``peak_torque_rise_nm``, how much larger the largest joint torque is over
  the ``response_window`` seconds from the onset (``[pulses]``);
- ``runs.npz``: every run's joint angles, reference, joint torques, tip force, and
  progress along the take's joint path, every reference period, with its arm and
  pulse.

The runs are spread over ``--workers`` processes.
"""

from __future__ import annotations

import argparse
import csv
import itertools
import os
import tomllib
from concurrent.futures import ProcessPoolExecutor
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
from numpy.typing import NDArray
from robot_esn import (
    FOLLOWING_WINDOW,
    RETURN_TOLERANCE,
    arm_metrics,
    posed,
    progress,
    progress_source,
    ringing_settings,
    tracker_settings,
)

from arm_esn_ctrl.autonomous import Setup, load_setup
from arm_esn_ctrl.demonstrations import endpoint_positions
from arm_esn_ctrl.disturbances import disturbance_spans, make_disturbance
from arm_esn_ctrl.esn import ReachingEsn
from arm_esn_ctrl.storage import resolve_run_path, start_run
from arm_esn_ctrl.tracking import (
    EsnSource,
    ReferenceSource,
    ReplaySource,
    TrackerConfig,
    gain_posture,
    task_joint_angles,
    track,
)

CHANNELS = ("q", "q_ref", "tau", "ext_force")  # the channels runs.npz keeps, every reference period


@dataclass(frozen=True)
class Pulse:
    """A tip force of ``force`` N for ``duration`` s from ``onset``, at ``angle_deg`` from the target's direction."""

    onset: float
    angle_deg: float
    force: float
    duration: float

    def disturbance(self) -> dict[str, Any]:
        """Its ``[disturbance]`` table (see :mod:`arm_esn_ctrl.disturbances`)."""
        return {
            "type": "push",
            "force": self.force,
            "onset": self.onset,
            "duration": self.duration,
            "angle_deg": self.angle_deg,
        }


def pulses(table: dict[str, Any]) -> list[Pulse]:
    """Every pulse of a ``[pulses]`` table: each force, then each onset, then each angle."""
    return [
        Pulse(float(onset), float(angle), float(force), float(table["duration"]))
        for force, onset, angle in itertools.product(table["forces"], table["onsets"], table["angles_deg"])
    ]


@dataclass
class Context:
    """What every run needs, loaded once per process."""

    esns: dict[str, ReachingEsn]
    setup: Setup
    simulator: dict[str, Any]
    tracker: TrackerConfig
    gains: tuple[NDArray[np.float64], NDArray[np.float64]]
    progress: dict[str, Any]
    evaluation: dict[str, Any]


def load_context(config: dict[str, Any]) -> Context:
    """Load the ESNs, the take, and the tracker of ``config``."""
    esns, trained_on = {}, None
    for table in config["esn"]:
        esn_path = resolve_run_path(table["model"])
        esns[table["key"]] = ReachingEsn.load(esn_path)
        with (esn_path.parent / "config.toml").open("rb") as f:
            demonstrations = tomllib.load(f)["demonstrations"]
        if trained_on not in (None, demonstrations):
            msg = f"the ESNs must be trained on the same take: {table['key']} was trained on {demonstrations}"
            raise ValueError(msg)
        trained_on = demonstrations
    assert trained_on is not None
    dt = next(iter(esns.values())).config.dt
    setup = load_setup({"demonstrations": trained_on, "esn": {"dt": dt}, "evaluation": config["evaluation"]})
    if len(setup.demos) != 1 or len(setup.starts) != 1:
        msg = "the runs are from one start posture, along one take: give one start and an ESN trained on one take"
        raise ValueError(msg)
    with (resolve_run_path(trained_on["run"]) / "config.toml").open("rb") as f:
        simulator = tomllib.load(f)["simulator"]
    settings = tracker_settings(config["tracker"])
    if len(settings) != 1:
        msg = "[tracker] must give one setting: one law, natural frequency, and damping ratio, or kp and kd"
        raise ValueError(msg)
    setting, tracker = settings[0], config["tracker"]
    tracker_config = TrackerConfig(
        setting.law,
        setting.omega,
        tracker["acceleration_filter"],
        damping=setting.damping,
        reference_velocity=tracker.get("reference_velocity", True),
        control_period=tracker.get("control_period"),
    )
    gains = setting.gains(tracker_config, setup.skeleton, gain_posture(setup.demos.values()))
    return Context(esns, setup, simulator, tracker_config, gains, config["progress"], config["evaluation"])


_context: Context | None = None  # this process's, set by init_worker


def init_worker(config: dict[str, Any]) -> None:
    """Load the context of a worker process."""
    global _context
    _context = load_context(config)


def run_pulse(arm: str, pulse: Pulse | None) -> tuple[dict[str, Any], dict[str, NDArray[np.float64]]]:
    """Run ``arm`` under ``pulse`` (None: undisturbed) in this worker; its metrics and its channels."""
    assert _context is not None
    return run_arm(_context, arm, pulse)


def run_arm(context: Context, arm: str, pulse: Pulse | None) -> tuple[dict[str, Any], dict[str, NDArray[np.float64]]]:
    """Run ``arm``, an ESN's key, ``replay``, or ``progress``, under ``pulse``; its metrics and its channels."""
    setup = context.setup
    start = setup.starts[0]
    take = next(iter(setup.demos.values()))
    period = next(iter(context.esns.values())).config.dt
    source: ReferenceSource
    if arm in context.esns:
        source = EsnSource(context.esns[arm])
    elif arm == "replay":
        source = ReplaySource(take)
    elif arm == "progress":
        source = progress_source(context.progress, take, period)
    else:
        msg = f"unknown arm {arm!r}"
        raise ValueError(msg)
    warmup_steps = next(iter(context.esns.values())).config.warmup_steps
    disturbance = None if pulse is None else pulse.disturbance()
    start_hand = endpoint_positions(setup.skeleton, start.q[np.newaxis])[0]
    duration = context.evaluation["duration"]
    log = track(
        posed(setup.skeleton, start.q),
        source,
        context.tracker,
        context.gains,
        period=period,
        warmup_steps=warmup_steps,
        duration=duration,
        dt=context.simulator["dt"],
        enforce_limits=context.simulator.get("enforce_limits", True),
        external_force=make_disturbance(disturbance, start_hand, setup.target, dt=context.simulator["dt"]),
    )
    evaluation = context.evaluation
    metrics = arm_metrics(
        log,
        0,
        setup,
        period,
        [0.0, duration],
        disturbance_spans(disturbance),
        evaluation.get("return_tolerance", RETURN_TOLERANCE),
        ringing_settings(evaluation),
        evaluation.get("following_window", FOLLOWING_WINDOW),
    )
    channels = {
        name: task_joint_angles(log, period, duration, name)
        if name in log.channel_names
        else np.zeros((len(setup.times), 2))  # an undisturbed run has no tip force
        for name in CHANNELS
    }
    channels["progress"] = progress(channels["q"], start.q, setup)
    nan = float("nan")
    pulse_columns = {"onset": nan, "angle_deg": nan, "force_n": nan, "duration_s": nan}
    if pulse is not None:
        pulse_columns = {
            "onset": pulse.onset,
            "angle_deg": pulse.angle_deg,
            "force_n": pulse.force,
            "duration_s": pulse.duration,
        }
    return {"arm": arm} | pulse_columns | metrics, channels


def against_undisturbed(
    rows: list[dict[str, Any]],
    channels: list[dict[str, NDArray[np.float64]]],
    times: NDArray[np.float64],
    window: float,
) -> None:
    """Add to each pulsed run's row its arrival shift, setback, and peak torque rise, against its arm undisturbed."""
    undisturbed = {row["arm"]: i for i, row in enumerate(rows) if not np.isfinite(row["onset"])}
    for row, run in zip(rows, channels, strict=True):
        nan = float("nan")
        if not np.isfinite(row["onset"]):
            row |= {"arrival_shift_s": nan, "setback": nan, "peak_torque_rise_nm": nan}
            continue
        base = undisturbed[row["arm"]]
        after = times > row["onset"] - 1e-9
        response = after & (times < row["onset"] + window + 1e-9)
        onset_progress = float(run["progress"][after][0])
        peak = float(np.abs(run["tau"][response]).max())
        row |= {
            "arrival_shift_s": row["arrival_time_s"] - rows[base]["arrival_time_s"],
            "setback": onset_progress - float(run["progress"][after].min()),
            "peak_torque_rise_nm": peak - float(np.abs(channels[base]["tau"][response]).max()),
        }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("config", type=Path, help="experiment configuration file (TOML)")
    parser.add_argument("--workers", type=int, default=max(1, (os.cpu_count() or 2) // 2), help="worker processes")
    args = parser.parse_args()

    config, run_dir = start_run(args.config)
    context = load_context(config)
    arms = [*context.esns, "replay", "progress"]
    jobs: list[tuple[str, Pulse | None]] = [(arm, pulse) for arm in arms for pulse in [None, *pulses(config["pulses"])]]
    print(f"{len(jobs)} runs: {', '.join(arms)}, each undisturbed and under {len(jobs) // len(arms) - 1} pulses")
    with ProcessPoolExecutor(args.workers, initializer=init_worker, initargs=(config,)) as pool:
        results = list(pool.map(run_pulse, *zip(*jobs, strict=True), chunksize=4))
    rows = [row for row, _ in results]
    channels = [run for _, run in results]
    times = context.setup.times
    against_undisturbed(rows, channels, times, config["pulses"]["response_window"])

    with (run_dir / "metrics.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    arrays: dict[str, Any] = {
        "times": times,
        "arm": np.array([row["arm"] for row in rows]),
        **{key: np.array([row[key] for row in rows]) for key in ("onset", "angle_deg", "force_n")},
    }
    arrays |= {name: np.array([run[name] for run in channels], dtype=np.float32) for name in channels[0]}
    np.savez_compressed(run_dir / "runs.npz", **arrays)
    print_summary(rows, arms)
    print(f"\nWrote the results to {run_dir}")


def print_summary(rows: list[dict[str, Any]], arms: list[str]) -> None:
    """Print, for each arm and force, the median deviation, return time, arrival shift, and setback."""
    for arm in arms:
        pulsed = [row for row in rows if row["arm"] == arm and np.isfinite(row["onset"])]
        for force in sorted({row["force_n"] for row in pulsed}):
            of = [row for row in pulsed if row["force_n"] == force]

            def median(key: str, runs: list[dict[str, Any]] = of) -> float:
                return float(np.nanmedian([row[key] for row in runs]))

            print(
                f"{arm:>8}, {force:g} N: off the path {1000 * median('off_path_m'):.1f} mm,"
                f" back in {median('return_time_s'):.2f} s, arrives {median('arrival_shift_s'):+.2f} s later,"
                f" setback {median('setback'):.3f}, following gain {median('following_gain'):.2f} (medians)"
            )


if __name__ == "__main__":
    main()
